"""Compile reviewed prerequisite metadata into allocation-once net35 data; no game/guide reads."""
import argparse,hashlib,json
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
root=Path(__file__).resolve().parents[1]
# Git's Windows checkout may use CRLF. Fingerprint the canonical source bytes.
raw=(root/'docs/accessibility/story-prerequisites.json').read_bytes().replace(b'\r\n',b'\n');d=json.loads(raw)
assert d['schema']==1 and len({f['field'] for f in d['fields']})==len(d['fields'])
q=lambda x:json.dumps(x,ensure_ascii=True)
lines=['// Generated by tools/compile_story_prerequisites.py from reviewed native-state metadata.','namespace Memoria.Accessibility.Navigation { public static class StoryPrerequisiteData {',f'public const string MetadataSHA256="{hashlib.sha256(raw).hexdigest()}";','public static readonly StoryPrerequisiteField[] All={']
for f in d['fields']:
    assert f['floor']<f['ceiling'] and len(f['director'])==64
    fields=[f'Field={f["field"]}',f'Kind=StoryPrerequisiteKind.{f["kind"]}',f'Floor={f["floor"]}',f'Ceiling={f["ceiling"]}',f'Milestone={f["milestone"]}',f'Director={q(f["director"])}',f'Bgi={q(f["bgi"])}',f'FlowerByte={f["flowerByte"]}']
    fields+=['Entries=new System.Collections.Generic.Dictionary<int,string>{'+','.join('{'+sid+','+q(h)+'}' for sid,h in f['entries'].items())+'}']
    fields+=['Players=new System.Collections.Generic.Dictionary<int,string>{'+','.join('{'+sid+','+q(h)+'}' for sid,h in f['players'].items())+'}']
    fields+=['Components=new int[]{'+','.join(map(str,f['components']))+'}']
    fields+=['Fragments=new System.Collections.Generic.Dictionary<int,int>{'+','.join('{'+sid+','+str(mask)+'}' for sid,mask in f['fragments'].items())+'}']
    routes=[]
    for r in f['routes']:routes.append('new StoryPrerequisiteRoute{Flags='+str(r['flags'])+',Component='+str(r['component'])+',Action='+q(r['action'])+',Sids=new int[]{'+','.join(map(str,r['sids']))+'}}')
    fields+=['Routes=new StoryPrerequisiteRoute[]{'+','.join(routes)+'}']
    lines.append('new StoryPrerequisiteField{'+','.join(fields)+'},')
lines+=['}; } }',''];text='\n'.join(lines);out=root/'Assembly-CSharp/Memoria/Accessibility/Navigation/Core/StoryPrerequisiteData.cs'
if a.check:assert out.read_text(encoding='utf-8')==text,'Regenerate prerequisite data'
else:out.write_text(text,encoding='utf-8')
print('PASS reviewed prerequisite metadata',len(d['fields']),'fields; compiler', 'verified' if a.check else 'generated')
